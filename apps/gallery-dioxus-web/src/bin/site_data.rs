//! Writes the data the Oxyn site is built from.
//!
//! ```text
//! cargo run -p oxyn-gallery-web --bin site-data -- site/src/generated
//! ```
//!
//! - `demos.json`: categories and every demo: metadata, controls, variants, keyboard,
//!   accessibility and responsive notes, plus the server-rendered HTML of the playground and of
//!   each variant (shown before the WASM loads, with JavaScript off, and to crawlers).
//! - `oxyn-components.css`: every component stylesheet of `oxyn-dioxus`, in one file.

#[cfg(not(target_arch = "wasm32"))]
fn main() {
    use oxyn_gallery_web::{Kind, catalog, render_html};
    use serde_json::{Value, json};

    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "site/src/generated".into());
    let out = std::path::PathBuf::from(out);
    std::fs::create_dir_all(&out).expect("create output dir");

    let cats: Vec<Value> = oxyn_gallery_web::categories()
        .iter()
        .map(|c| json!({ "slug": c.slug, "name": c.name, "blurb": c.blurb }))
        .collect();

    let mut demos = Vec::new();
    for d in catalog() {
        let controls: Vec<Value> = d
            .controls
            .iter()
            .map(|c| {
                let (kind, extra) = match &c.kind {
                    Kind::Select(o) => ("select", json!({ "options": o })),
                    Kind::Toggle => ("toggle", json!({})),
                    Kind::Range(a, b, s) => ("range", json!({ "min": a, "max": b, "step": s })),
                    Kind::Text => ("text", json!({})),
                };
                json!({ "key": c.key, "label": c.label, "kind": kind, "default": c.default, "extra": extra })
            })
            .collect();
        let variants: Vec<Value> = d
            .variants
            .iter()
            .enumerate()
            .map(|(i, v)| {
                json!({
                    "name": v.name,
                    "note": v.note,
                    "set": v.set.iter().map(|(k, x)| json!([k, x])).collect::<Vec<_>>(),
                    "code": (d.code)(&d.values(Some(i))),
                    "html": render_html(d.slug, Some(i), false),
                })
            })
            .collect();
        demos.push(json!({
            "slug": d.slug,
            "name": d.name,
            "category": d.category,
            "summary": d.summary,
            "dioxus": d.dioxus,
            "gpui": d.gpui,
            "spec": d.spec,
            "source": d.source,
            "controls": controls,
            "variants": variants,
            "keyboard": d.keyboard.iter().map(|(k, x)| json!([k, x])).collect::<Vec<_>>(),
            "a11y": d.a11y,
            "responsive": d.responsive,
            "height": d.height,
            "live": d.live,
            "code": (d.code)(&d.values(None)),
            "html": render_html(d.slug, None, true),
        }));
    }
    let doc = json!({ "categories": cats, "demos": demos });
    std::fs::write(
        out.join("demos.json"),
        serde_json::to_string(&doc).expect("json"),
    )
    .expect("write demos.json");

    let css = [
        oxyn_dioxus::STATUS_INDICATOR_CSS,
        oxyn_dioxus::GLYPH_LOADER_CSS,
        oxyn_dioxus::STATUS_TEXT_CSS,
        oxyn_dioxus::COMPOSER_CSS,
        oxyn_dioxus::RUN_CSS,
        oxyn_dioxus::HITL_CSS,
        oxyn_dioxus::PRIMITIVES_CSS,
    ]
    .join("\n");
    std::fs::write(
        out.join("oxyn-components.css"),
        format!("/* @generated by `site-data` from oxyn-dioxus. Do not edit. */\n{css}"),
    )
    .expect("write css");
    eprintln!(
        "site-data: {} demos, {} categories → {}",
        doc["demos"].as_array().map_or(0, Vec::len),
        doc["categories"].as_array().map_or(0, Vec::len),
        out.display()
    );
}

#[cfg(target_arch = "wasm32")]
fn main() {}

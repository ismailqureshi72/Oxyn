# Regenerates site/src/components/v2/brands.ts: coloured brand marks for the site chrome (the
# "Open in" AI buttons, the MCP button and the agent list on the landing page).
# Sources: Lobe Icons (@lobehub/icons-static-svg, MIT) and Simple Icons (CC0); credits are in
# THIRD_PARTY_NOTICES.md. Usage: BRAND_SRC=<dir with si/ and lobe/> python3 scripts/brand/gen_site_brands.py
import os, re, json
B = os.environ.get("BRAND_SRC", "brand-src")
OUT = os.path.join(os.path.dirname(__file__), "../../site/src/components/v2/brands.ts")
# id, title, source, file, official hex for single-colour marks (None = the file's own colours)
MARKS = [
    ("claude", "Claude", "lobe", "claude-color", None),
    ("chatgpt", "ChatGPT", "lobe", "openai", "000000"),
    ("cursor", "Cursor", "lobe", "cursor", "000000"),
    ("v0", "v0", "lobe", "v0", "000000"),
    ("mcp", "Model Context Protocol", "lobe", "mcp", "000000"),
    ("claude-code", "Claude Code", "lobe", "claudecode-color", None),
    ("codex", "Codex", "lobe", "codex-color", None),
    ("windsurf", "Windsurf", "si", "windsurf", "0B100F"),
    ("github-copilot", "GitHub Copilot", "lobe", "githubcopilot", "000000"),
    ("gemini-cli", "Gemini CLI", "lobe", "gemini-color", None),
    ("zed", "Zed", "si", "zedindustries", "084CCF"),
    ("cline", "Cline", "si", "cline", "18181B"),
    ("opencode", "OpenCode", "lobe", "opencode", "000000"),
    ("amp", "Amp", "lobe", "amp-color", None),
]

def dark(hexv):
    r, g, b = (int(hexv[i:i + 2], 16) for i in (0, 2, 4))
    return (0.2126 * r + 0.7152 * g + 0.0722 * b) < 60

out = []
for mid, title, src, f, hexv in MARKS:
    path = f"{B}/{'lobe/icons' if src == 'lobe' else 'si/icons'}/{f}.svg"
    svg = open(path).read().strip()
    vb = re.search(r'viewBox="([^"]+)"', svg).group(1)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
    attrs = ""
    m = re.search(r'fill-rule="([^"]+)"', svg.split(">", 1)[0])
    if m:
        attrs += f' fill-rule="{m.group(1)}"'
    if hexv:
        attrs += f' fill="#{hexv}"'
        inner = inner.replace('fill="currentColor"', f'fill="#{hexv}"')
    # Give gradient ids a per-mark prefix so two marks never share one.
    inner = re.sub(r'id="([^"]+)"', lambda x: f'id="ox-{mid}-{x.group(1)}"', inner)
    inner = re.sub(r'url\(#([^)]+)\)', lambda x: f'url(#ox-{mid}-{x.group(1)})', inner)
    body = f'<svg viewBox="{vb}" width="16" height="16"{attrs} aria-hidden="true" focusable="false">{inner}</svg>'
    out.append((mid, title, body, bool(hexv) and dark(hexv), "Lobe Icons (MIT)" if src == "lobe" else "Simple Icons (CC0)"))

with open(OUT, "w") as fh:
    fh.write("// Generated by scripts/brand/gen_site_brands.py; do not edit by hand.\n")
    fh.write("// Brand marks in their official colours: Lobe Icons (MIT) and Simple Icons (CC0). Trademarks\n")
    fh.write("// belong to their owners; see THIRD_PARTY_NOTICES.md.\n\n")
    fh.write("export interface BrandMark {\n  title: string;\n  svg: string;\n  /** Near-black mark: drawn on a light chip in dark mode. */\n  dark: boolean;\n  source: string;\n}\n\n")
    fh.write("export const brands: Record<string, BrandMark> = {\n")
    for mid, title, body, dk, srcname in out:
        fh.write(f"  {json.dumps(mid)}: {{ title: {json.dumps(title)}, dark: {str(dk).lower()}, source: {json.dumps(srcname)}, svg: {json.dumps(body)} }},\n")
    fh.write("};\n\n")
    fh.write("/** A mark as inline HTML: a chip span the CSS gives a light backing in dark mode when needed. */\n")
    fh.write("export const mark = (id: string, cls = ''): string => {\n  const b = brands[id];\n  if (!b) return '';\n  return `<span class=\"x-brand${cls ? ' ' + cls : ''}\"${b.dark ? ' data-dark' : ''}>${b.svg}</span>`;\n};\n")
print(len(out), "marks")

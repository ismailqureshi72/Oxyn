//! Writes `tokens/dist/oxyn.css`: one custom property per semantic, motion and theme token.

use std::fmt::Write;

use serde_json::Value;

use crate::{contrast::hex_alpha, model::TokenSet};

fn var(path: &str) -> String {
    format!("--oxyn-{}", path.replace('.', "-"))
}

fn num(x: f64) -> String {
    let s = format!("{x}");
    s.strip_suffix(".0").map(str::to_owned).unwrap_or(s)
}

fn color(v: &Value) -> String {
    let (c, a) = hex_alpha(v);
    if a < 1.0 {
        let [r, g, b] = c.0;
        format!("rgb({r} {g} {b} / {})", num(a))
    } else {
        c.hex()
    }
}

fn dim(v: &Value) -> String {
    format!(
        "{}{}",
        num(v["value"].as_f64().expect("dimension")),
        v["unit"].as_str().expect("unit")
    )
}

fn families(v: &Value) -> String {
    let quote = |s: &str| {
        if s.contains(' ') || s.chars().next().is_some_and(|c| c.is_ascii_uppercase()) {
            format!("\"{s}\"")
        } else {
            s.to_owned()
        }
    };
    match v {
        Value::Array(a) => a
            .iter()
            .map(|x| quote(x.as_str().unwrap()))
            .collect::<Vec<_>>()
            .join(", "),
        Value::String(s) => quote(s),
        _ => panic!("font family"),
    }
}

/// `(suffix, css value)` pairs for one token; composites expand into several properties.
fn values(ty: &str, v: &Value) -> Vec<(String, String)> {
    let one = |s: String| vec![(String::new(), s)];
    match ty {
        "color" => one(color(v)),
        "dimension" | "duration" => one(dim(v)),
        "number" => one(num(v.as_f64().expect("number"))),
        "fontWeight" => one(v.to_string()),
        "fontFamily" => one(families(v)),
        "cubicBezier" => {
            let a: Vec<String> = v
                .as_array()
                .unwrap()
                .iter()
                .map(|x| num(x.as_f64().unwrap()))
                .collect();
            one(format!("cubic-bezier({})", a.join(", ")))
        }
        "typography" => vec![
            ("-font-family".into(), families(&v["fontFamily"])),
            ("-font-size".into(), dim(&v["fontSize"])),
            ("-font-weight".into(), v["fontWeight"].to_string()),
            ("-letter-spacing".into(), dim(&v["letterSpacing"])),
            (
                "-line-height".into(),
                num(v["lineHeight"].as_f64().unwrap()),
            ),
        ],
        "shadow" => one(format!(
            "{} {} {} {} {}",
            dim(&v["offsetX"]),
            dim(&v["offsetY"]),
            dim(&v["blur"]),
            dim(&v["spread"]),
            color(&v["color"])
        )),
        "border" => one(format!("{} solid {}", dim(&v["width"]), color(&v["color"]))),
        other => panic!("no CSS mapping for $type {other}"),
    }
}

fn block<'a>(
    out: &mut String,
    set: &TokenSet,
    items: impl Iterator<Item = (&'a str, &'a crate::model::Token)>,
) {
    for (rel, tok) in items {
        let v = set.resolved(&tok.path).expect("validated");
        for (suffix, css) in values(&tok.ty, &v) {
            writeln!(out, "  {}{suffix}: {css};", var(rel)).unwrap();
        }
    }
}

pub fn generate(tokens: &TokenSet, motion: &TokenSet) -> String {
    let mut o = String::new();
    o.push_str("/* @generated by `cargo run -p oxyn-tokens-gen`. Do not edit by hand. */\n");
    o.push_str("/* Source: tokens/oxyn.tokens.json, tokens/oxyn.motion.json (DTCG 2025.10). */\n");
    o.push_str("/* Themes: set data-oxyn-theme=\"dark|light|hc-dark\" on any element; dark is the default. */\n\n");

    o.push_str(":root {\n");
    block(&mut o, tokens, tokens.under("semantic"));
    let mot = motion.tokens.iter().map(|t| {
        let rel = t.path.strip_prefix("motion.").unwrap_or(&t.path);
        (rel, t)
    });
    block(&mut o, motion, mot);
    o.push_str("}\n");

    let themes = tokens.themes();
    for (i, th) in themes.iter().enumerate() {
        o.push('\n');
        if i == 0 {
            writeln!(o, ":root,\n[data-oxyn-theme=\"{th}\"] {{").unwrap();
        } else {
            writeln!(o, "[data-oxyn-theme=\"{th}\"] {{").unwrap();
        }
        let dark = !th.contains("light");
        writeln!(
            o,
            "  color-scheme: {};",
            if dark { "dark" } else { "light" }
        )
        .unwrap();
        block(&mut o, tokens, tokens.under(&format!("theme.{th}")));
        o.push_str("}\n");
    }
    o
}
